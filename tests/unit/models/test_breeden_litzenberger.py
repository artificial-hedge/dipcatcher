# ---------------------------------------------------------------------------


def test_extract_returns_result_shape() -> None:
    res = _extract(CLEAN)
    assert isinstance(res, RNDResult)
    assert res.strikes.shape == res.density.shape == res.density_raw.shape
    assert res.observed_mask.dtype == bool
    assert np.all(np.diff(res.strikes) > 0.0)


def test_density_recovers_true_clean() -> None:
    res = _extract(CLEAN)
    rep = arbitrage_report(
        res,
        model_density=CLEAN.density_on(res.strikes),
        reference_moments=CLEAN.true_moments,
    )
    assert rep["l1_distance"] < 0.15
    assert rep["kl_divergence"] < 0.5


def test_repaired_density_is_a_density() -> None:
    res = _extract(CLEAN)
    assert (res.density >= 0.0).all()
    assert np.isfinite(res.density).all()
    assert abs(np.trapezoid(res.density, res.strikes) - 1.0) < 1e-9


def test_mass_defect_closed_by_repair() -> None:
    res = _extract(CLEAN)
    assert res.diagnostics["mass_defect_after_repair"] < 1e-9
    # raw extraction over a finite grid carries a nonzero defect
    assert abs(res.diagnostics["mass_defect_raw"]) < 0.05


def test_density_peak_region_matches_true_mode() -> None:
    res = _extract(CLEAN)
    q = CLEAN.density_on(res.strikes)
    mode_hat = res.strikes[np.argmax(res.density[res.observed_mask])]
    mode_true = res.strikes[res.observed_mask][np.argmax(q[res.observed_mask])]
    assert abs(mode_hat - mode_true) / res.forward < 0.15


