def test_fixture_call_price_matches_payoff_integral() -> None:
    """Closed-form mixture calls must match ∫ (S-K)+ q(S) dS on the fine grid."""
    fx = CLEAN
    payoff = np.trapezoid(
        np.maximum(fx.fine_grid[:, None] - fx.strikes[None, :], 0.0) * fx.true_density[:, None],
        fx.fine_grid,
        axis=0,
    )
    disc = np.exp(-fx.r * fx.maturity)
    model = fx.call_price_on(fx.strikes) / disc
    rel = np.abs(model - payoff) / payoff
    mid = payoff > 1.0  # only compare where the payoff is meaningfully covered
    assert mid.sum() >= 10
    assert (rel[mid] < 0.05).all()


def test_fixture_true_moments_match_density() -> None:
    """Analytic raw-moment identities agree with numerical integration."""
    fx = CLEAN
    mom = implied_moments(fx.fine_grid, fx.true_density)
    assert abs(mom["mean"] - fx.true_moments["mean"]) < 0.5
    assert abs(mom["variance"] - fx.true_moments["variance"]) / fx.true_moments["variance"] < 0.02
    assert abs(mom["skewness"] - fx.true_moments["skewness"]) < 0.05
    assert abs(mom["excess_kurtosis"] - fx.true_moments["excess_kurtosis"]) < 0.2


def test_fixture_martingale_calibration() -> None:
    assert abs(CLEAN.true_moments["mean"] - CLEAN.forward) < 1e-8
    assert CLEAN.true_moments["skewness"] < 0.0


