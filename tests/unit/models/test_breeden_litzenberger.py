def test_near_lognormal_limit_positive_skew() -> None:
    """Shrinking the crash component (weight -> 0) approaches a pure
    lognormal, which has *positive* skew — opposite sign of the default."""
    fx = synthetic_mixture_smile(seed=5, noise_std=0.0, weight=0.02)
    assert fx.true_moments["skewness"] > 0.0
    res = _extract(fx)
    mom = implied_moments(res.strikes, res.density)
    assert mom["skewness"] > 0.0


