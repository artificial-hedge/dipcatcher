"""Tests for models/breeden_litzenberger.py — BL RND extraction + moments.

SYNTHETIC: every smile is generated by the in-module lognormal-mixture DGP
(:func:`synthetic_mixture_smile`); no market data. Assertions are correctness
checks — density L1/KL error, moment recovery, mass normalization, arb-screen
fail-closed behavior — never market evidence.

References exercised: Breeden & Litzenberger (1978) J. Business 51(4);
Shimko (1993) RISK 6(4); Aït-Sahalia & Lo (1998) J. Finance 53(2);
Figlewski (2010); Malz (2014) NY Fed Staff Report 677.
"""

from __future__ import annotations

import numpy as np
import pytest

from quant_fund.models.breeden_litzenberger import (
    RNDResult,
    arbitrage_report,
    bench_breeden_litzenberger,
    extract_rnd,
    implied_moments,
    synthetic_mixture_smile,
)

CLEAN = synthetic_mixture_smile(seed=3, noise_std=0.0)
NOISY = synthetic_mixture_smile(seed=11, noise_std=0.004)
NARROW = synthetic_mixture_smile(seed=4, noise_std=0.0, strike_lo_log=-0.5, strike_hi_log=0.45)


def _extract(fx) -> RNDResult:
    return extract_rnd(
        fx.strikes,
        fx.call_prices,
        forward=fx.forward,
        r=fx.r,
        maturity=fx.maturity,
    )


