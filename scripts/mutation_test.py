def resolve_target(target: str | Path, repo: Path = REPO) -> Path:
    """Validate the target file and return its resolved path."""
    repo_root = repo.resolve()
    path = Path(target)
    if not path.is_absolute():
        path = repo_root / path
    resolved = path.resolve()
    if not resolved.is_file():
        raise MutationTestError(f"target does not exist or is not a file: {resolved}")
    if resolved.suffix != ".py":
        raise MutationTestError(f"target must be a .py file: {resolved}")
    if repo_root not in resolved.parents:
        raise MutationTestError(f"target is outside the repo ({repo_root}): {resolved}")
    if not (resolved.parent / "__init__.py").is_file():
        raise MutationTestError(
            f"target is not part of an importable package (no __init__.py in {resolved.parent})"
        )
    return resolved


def module_name_for(target: Path) -> str:
    """Dotted module name for *target* (walks up while ``__init__.py`` exists)."""
    parts = [target.stem]
    parent = target.parent
    while (parent / "__init__.py").is_file():
        parts.append(parent.name)
        parent = parent.parent
    if len(parts) == 1:
        raise MutationTestError(f"target is not inside a package: {target}")
    return ".".join(reversed(parts))


def validate_selectors(selectors: Sequence[str], repo: Path = REPO) -> tuple[str, ...]:
    """Validate pytest selectors; refuse empty or option-like/injection inputs."""
    if not selectors:
        raise MutationTestError("pytest selector list is empty; pass at least one --pytest target")
    repo_root = repo.resolve()
    cleaned: list[str] = []
    for selector in selectors:
        if not isinstance(selector, str) or not selector.strip():
            raise MutationTestError(f"pytest selector must be a non-empty string: {selector!r}")
        text = selector.strip()
        if text.startswith("-"):
            raise MutationTestError(f"pytest selector must not look like an option: {text!r}")
        path_part = text.split("::", 1)[0]
        candidate = Path(path_part)
        if not candidate.is_absolute():
            candidate = repo_root / candidate
        try:
            resolved = candidate.resolve()
        except OSError as exc:
            raise MutationTestError(f"unreadable pytest selector path {text!r}: {exc}") from exc
        if repo_root != resolved and repo_root not in resolved.parents:
            raise MutationTestError(f"pytest selector points outside the repo: {text!r}")
        cleaned.append(text)
    return tuple(cleaned)


