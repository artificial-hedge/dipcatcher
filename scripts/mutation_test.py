def main(argv: Sequence[str] | None = None, *, repo: Path = REPO) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--target", required=True, help="Python file to mutate (must live inside the repo)"
    )
    parser.add_argument(
        "--pytest",
        action="append",
        default=[],
        dest="selectors",
        help="pytest selector (path or path::nodeid) for the killing subset; repeatable",
    )
    parser.add_argument("--max-mutants", type=int, default=DEFAULT_MAX_MUTANTS)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--timeout", type=float, default=DEFAULT_TIMEOUT_S, help="per-run seconds")
    parser.add_argument("--json-out", type=Path, default=None)
    parser.add_argument(
        "--min-score",
        type=float,
        default=None,
        help="optional gate in [0, 1]; exit 1 when the mutation score is below it",
    )
    parser.add_argument(
        "--list-mutants",
        action="store_true",
        help="enumerate mutants and exit without running pytest",
    )
    args = parser.parse_args(argv)

    try:
        if args.timeout <= 0:
            raise MutationTestError(f"--timeout must be > 0, got {args.timeout}")
        if args.max_mutants < 1:
            raise MutationTestError(f"--max-mutants must be >= 1, got {args.max_mutants}")
        if args.min_score is not None and not 0.0 <= args.min_score <= 1.0:
            raise MutationTestError(f"--min-score must be in [0, 1], got {args.min_score}")
        if not args.list_mutants:
            validate_selectors(args.selectors, repo)
        target = resolve_target(args.target, repo)
        module_name = module_name_for(target)
        source = target.read_text(encoding="utf-8")
        mutants = generate_mutants(source, filename=str(target))
        if not mutants:
            raise MutationTestError(f"{target}: no mutants generated; refusing to run")
        sampled = sample_mutants(mutants, args.max_mutants, args.seed)

        if args.list_mutants:
            print(f"{target} ({module_name}): {len(mutants)} mutants available")
            for mutant in sampled:
                print(
                    f"  {mutant.mutant_id} line {mutant.lineno}: "
                    f"[{mutant.operator}] {mutant.description}"
                )
            return 0

        with tempfile.TemporaryDirectory(prefix="mutation-overlay-") as tmp:
            overlay_dir = Path(tmp) / "overlay"
            results = run_campaign(
                sampled,
                args.selectors,
                repo=repo,
                overlay_dir=overlay_dir,
                module_name=module_name,
                timeout_s=args.timeout,
                original_source=source,
            )
        report = build_report(
            target,
            module_name,
            tuple(args.selectors),
            args.seed,
            args.timeout,
            len(mutants),
            results,
            min_score=args.min_score,
        )
        print(format_summary(report))
        if args.json_out is not None:
            args.json_out.parent.mkdir(parents=True, exist_ok=True)
            args.json_out.write_text(
                json.dumps(report_to_dict(report), indent=2) + "\n", encoding="utf-8"
            )
            print(f"wrote {args.json_out}")
        if report.counts["error"] > 0:
            print(
                f"error: {report.counts['error']} mutant run(s) hit pytest internal/usage "
                "errors; failing closed",
                file=sys.stderr,
            )
            return 2
        if args.min_score is not None and report.score < args.min_score:
            return 1
        return 0
    except (MutationTestError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
