def build_report(
    target: Path,
    module_name: str,
    selectors: Sequence[str],
    seed: int,
    timeout_s: float,
    total_mutants: int,
    results: Sequence[MutantResult],
    min_score: float | None = None,
) -> CampaignReport:
    """Aggregate results into a report; score = (killed+timeout)/(sampled-error)."""
    counts = {"killed": 0, "survived": 0, "timeout": 0, "error": 0}
    for result in results:
        counts[result.status] += 1
    attempted = len(results) - counts["error"]
    score = (counts["killed"] + counts["timeout"]) / attempted if attempted else 0.0
    rows = [asdict(result) for result in results]
    return CampaignReport(
        created_utc=datetime.now(UTC).isoformat(),
        target=str(target),
        module=module_name,
        selectors=tuple(selectors),
        seed=seed,
        timeout_s=timeout_s,
        total_mutants=total_mutants,
        sampled=len(results),
        counts=counts,
        score=round(score, 4),
        min_score=min_score,
        results=rows,
        survivors=[row for row in rows if row["status"] == "survived"],
    )


def report_to_dict(report: CampaignReport) -> dict[str, object]:
    payload = asdict(report)
    payload["selectors"] = list(report.selectors)
    return payload


def format_summary(report: CampaignReport) -> str:
    counts = report.counts
    lines = [
        f"target: {report.target} ({report.module})",
        f"selectors: {' '.join(report.selectors)}",
        f"mutants: {report.total_mutants} available, {report.sampled} sampled "
        f"(seed={report.seed}, max-mutants cap)",
        f"killed={counts['killed']} survived={counts['survived']} "
        f"timeout={counts['timeout']} error={counts['error']}",
        f"mutation score: {report.score:.2%}  [(killed+timeout)/(sampled-error)]",
    ]
    if report.survivors:
        lines.append("survivors:")
        for row in report.survivors:
            lines.append(
                f"  {row['mutant_id']} line {row['lineno']}: "
                f"[{row['operator']}] {row['description']}"
            )
    if report.min_score is not None:
        lines.append(
            "min-score gate: "
            + ("PASS" if report.score >= report.min_score else "FAIL")
            + f" (>= {report.min_score:.2%})"
        )
    lines.append(WATERMARK)
    return "\n".join(lines)


