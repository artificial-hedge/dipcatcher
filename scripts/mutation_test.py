def write_overlay(overlay_dir: Path, module_source: str) -> Path:
    """Write ``sitecustomize.py`` + ``mutant_module.py``; return the mutant path."""
    overlay_dir.mkdir(parents=True, exist_ok=True)
    (overlay_dir / "sitecustomize.py").write_text(SITECUSTOMIZE_SOURCE, encoding="utf-8")
    mutant_file = overlay_dir / "mutant_module.py"
    mutant_file.write_text(module_source, encoding="utf-8")
    return mutant_file


def overlay_env(
    overlay_dir: Path,
    module_name: str,
    mutant_file: Path,
    base_env: os._Environ[str] | dict[str, str] | None = None,
) -> dict[str, str]:
    """Subprocess env: overlay first on PYTHONPATH + redirect env vars."""
    env = dict(os.environ if base_env is None else base_env)
    existing = env.get("PYTHONPATH", "")
    env["PYTHONPATH"] = f"{overlay_dir}{os.pathsep}{existing}" if existing else str(overlay_dir)
    env["MUTATION_TARGET_MODULE"] = module_name
    env["MUTATION_TARGET_FILE"] = str(mutant_file)
    # Never let an ambient coverage subprocess hook pollute campaign runs.
    env.pop("COVERAGE_PROCESS_START", None)
    env.pop("COVERAGE_PROCESS_CONFIG", None)
    return env


def build_command(selectors: Sequence[str]) -> list[str]:
    """Pytest command for one campaign run (fail-fast, no cache writes)."""
    return [
        sys.executable,
        "-m",
        "pytest",
        "-x",
        "-q",
        "--no-header",
        "-p",
        "no:cacheprovider",
        *selectors,
    ]


def _tail(text: str, lines: int = _OUTPUT_TAIL_LINES) -> str:
    stripped = text.strip()
    if not stripped:
        return ""
    return "\n".join(stripped.splitlines()[-lines:])


def default_runner(
    command: list[str], cwd: Path, env: dict[str, str], timeout_s: float
) -> RunOutcome:
    """Real subprocess runner with a hard timeout."""
    start = time.perf_counter()
    try:
        completed = subprocess.run(
            command,
            cwd=cwd,
            env=env,
            timeout=timeout_s,
            capture_output=True,
            text=True,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        partial = exc.stdout
        tail = _tail(
            partial.decode("utf-8", "replace") if isinstance(partial, bytes) else partial or ""
        )
        return RunOutcome(returncode=None, duration_s=time.perf_counter() - start, output_tail=tail)
    output = _tail(f"{completed.stdout}\n{completed.stderr}")
    return RunOutcome(
        returncode=completed.returncode,
        duration_s=time.perf_counter() - start,
        output_tail=output,
    )


def classify(returncode: int | None) -> str:
    """Map a pytest exit code onto a mutant verdict (see module docstring).

    Exit 4 (usage error / conftest ImportError) counts as ``killed``: the
    preflight baseline proved the command line is valid, so a 4 during the
    campaign means the mutated module crashed pytest's startup imports (this
    repo's ``tests/conftest.py`` eagerly imports the research layer). 3/5 stay
    ``error``: genuinely ambiguous harness states.
    """
    if returncode is None:
        return "timeout"
    if returncode == 0:
        return "survived"
    if returncode in (1, 2, 4):
        return "killed"
    return "error"


def _preflight(
    selectors: Sequence[str],
    repo: Path,
    overlay_dir: Path,
    module_name: str,
    original_source: str,
    timeout_s: float,
    runner: Runner,
) -> None:
    """Fail closed unless the baseline passes and the sentinel is killed."""
    command = build_command(selectors)

    mutant_file = write_overlay(overlay_dir, original_source)
    env = overlay_env(overlay_dir, module_name, mutant_file)
    outcome = runner(command, repo, env, timeout_s)
    status = classify(outcome.returncode)
    if status != "survived":
        raise MutationTestError(
            f"baseline pytest run did not pass ({status}, rc={outcome.returncode}); "
            f"refusing to mutate against a red suite.\n--- output tail ---\n{outcome.output_tail}"
        )

    mutant_file = write_overlay(overlay_dir, SENTINEL_SOURCE)
    env = overlay_env(overlay_dir, module_name, mutant_file)
    outcome = runner(command, repo, env, timeout_s)
    status = classify(outcome.returncode)
    if status != "killed":
        raise MutationTestError(
            f"sentinel overlay was not killed ({status}, rc={outcome.returncode}); the overlay "
            "did not redirect imports, or the pytest selector never imports the target module. "
            f"Refusing to run.\n--- output tail ---\n{outcome.output_tail}"
        )


def run_campaign(
    mutants: Sequence[Mutant],
    selectors: Sequence[str],
    repo: Path,
    overlay_dir: Path,
    module_name: str,
    timeout_s: float,
    runner: Runner | None = None,
    original_source: str | None = None,
    preflight: bool = True,
) -> list[MutantResult]:
    """Run every mutant through the pytest subset, recording verdicts."""
    if runner is None:  # late-bound so tests can monkeypatch default_runner
        runner = default_runner
    command = build_command(selectors)
    if preflight:
        if original_source is None:
            raise MutationTestError("preflight requires original_source")
        _preflight(selectors, repo, overlay_dir, module_name, original_source, timeout_s, runner)
    results: list[MutantResult] = []
    for mutant in mutants:
        mutant_file = write_overlay(overlay_dir, mutant.source)
        env = overlay_env(overlay_dir, module_name, mutant_file)
        outcome = runner(command, repo, env, timeout_s)
        results.append(
            MutantResult(
                mutant_id=mutant.mutant_id,
                operator=mutant.operator,
                lineno=mutant.lineno,
                description=mutant.description,
                status=classify(outcome.returncode),
                returncode=outcome.returncode,
                duration_s=round(outcome.duration_s, 3),
            )
        )
    return results


