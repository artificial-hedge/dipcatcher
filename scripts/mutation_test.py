@dataclass(frozen=True)
class _Spec:
    """A pending single-node edit, with closures bound to one parsed tree."""

    operator: str
    lineno: int
    description: str
    apply: Callable[[], None]


def _swap_compare_op(node: ast.Compare, position: int, replacement: type[ast.cmpop]) -> None:
    node.ops[position] = replacement()


def _swap_boolop(node: ast.BoolOp, replacement: type[ast.boolop]) -> None:
    node.op = replacement()


def _set_constant(node: ast.Constant, value: Any) -> None:
    node.value = value


def _insert_negation(node: ast.If | ast.While | ast.IfExp | ast.Assert, test: ast.expr) -> None:
    node.test = ast.UnaryOp(op=ast.Not(), operand=test)


def _remove_negation(node: ast.If | ast.While | ast.IfExp | ast.Assert, inner: ast.expr) -> None:
    node.test = inner


def _collect_specs(tree: ast.AST) -> list[_Spec]:
    """Enumerate every single-edit mutation of *tree* in deterministic order.

    ``ast.walk`` is breadth-first over a stable child order, so re-parsing the
    same source reproduces the same spec list index-for-index; materializing
    mutant *i* re-parses and applies spec *i* on the fresh tree.
    """
    specs: list[_Spec] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Compare):
            for position, op in enumerate(node.ops):
                for replacement in COMPARISON_SWAPS.get(type(op), ()):
                    name = f"{type(op).__name__}->{replacement.__name__}"
                    specs.append(
                        _Spec(
                            operator="comparison-swap",
                            lineno=node.lineno,
                            description=f"{name} (line {node.lineno})",
                            apply=partial(_swap_compare_op, node, position, replacement),
                        )
                    )
        elif isinstance(node, ast.BoolOp):
            bool_replacement: type[ast.boolop] = ast.Or if isinstance(node.op, ast.And) else ast.And
            name = f"{type(node.op).__name__}->{bool_replacement.__name__}"
            specs.append(
                _Spec(
                    operator="boolop-swap",
                    lineno=node.lineno,
                    description=f"{name} (line {node.lineno})",
                    apply=partial(_swap_boolop, node, bool_replacement),
                )
            )
        elif isinstance(node, ast.Constant):
            value = node.value
            if isinstance(value, bool):
                specs.append(
                    _Spec(
                        operator="const-bool-flip",
                        lineno=node.lineno,
                        description=f"{value}->{not value} (line {node.lineno})",
                        apply=partial(_set_constant, node, not value),
                    )
                )
            elif isinstance(value, int):
                specs.append(
                    _Spec(
                        operator="numeric-perturb",
                        lineno=node.lineno,
                        description=f"int {value}->{value + 1} (line {node.lineno})",
                        apply=partial(_set_constant, node, value + 1),
                    )
                )
            elif isinstance(value, float):
                specs.append(
                    _Spec(
                        operator="numeric-perturb",
                        lineno=node.lineno,
                        description=f"float {value}->{value + 1.0} (line {node.lineno})",
                        apply=partial(_set_constant, node, value + 1.0),
                    )
                )
        elif isinstance(node, _NEGATION_SITES):
            test = node.test
            if isinstance(test, ast.UnaryOp) and isinstance(test.op, ast.Not):
                specs.append(
                    _Spec(
                        operator="negation-removal",
                        lineno=node.lineno,
                        description=f"drop `not` from test (line {node.lineno})",
                        apply=partial(_remove_negation, node, test.operand),
                    )
                )
            else:
                specs.append(
                    _Spec(
                        operator="negation-insertion",
                        lineno=node.lineno,
                        description=f"insert `not` into test (line {node.lineno})",
                        apply=partial(_insert_negation, node, test),
                    )
                )
    return specs


def generate_mutants(source: str, filename: str = "<target>") -> list[Mutant]:
    """Materialize every single-edit mutant of *source* (deterministic order)."""
    try:
        tree = ast.parse(source, filename=filename)
    except SyntaxError as exc:
        raise MutationTestError(f"{filename}: target does not parse: {exc}") from exc
    specs = _collect_specs(tree)
    mutants: list[Mutant] = []
    for index, spec in enumerate(specs):
        fresh = ast.parse(source, filename=filename)
        fresh_specs = _collect_specs(fresh)
        fresh_specs[index].apply()
        mutated = ast.unparse(fresh)
        try:
            compile(mutated, filename, "exec")
        except SyntaxError as exc:  # pragma: no cover - unparse of a valid AST
            raise MutationTestError(f"mutant M{index:04d} does not compile: {exc}") from exc
        mutants.append(
            Mutant(
                mutant_id=f"M{index:04d}",
                operator=spec.operator,
                lineno=spec.lineno,
                description=spec.description,
                source=mutated,
            )
        )
    return mutants


def sample_mutants(mutants: Sequence[Mutant], max_mutants: int, seed: int) -> list[Mutant]:
    """Cap the campaign at *max_mutants* via a seeded sample (order preserved)."""
    if max_mutants < 1:
        raise MutationTestError(f"--max-mutants must be >= 1, got {max_mutants}")
    if len(mutants) <= max_mutants:
        return list(mutants)
    picks = sorted(random.Random(seed).sample(range(len(mutants)), max_mutants))
    return [mutants[i] for i in picks]


