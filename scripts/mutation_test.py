WATERMARK = "test-suite diagnostic; not market evidence; no live-PnL claim"

DEFAULT_TIMEOUT_S = 120.0
DEFAULT_MAX_MUTANTS = 50
DEFAULT_SEED = 0
_OUTPUT_TAIL_LINES = 20

# Documented comparison-operator replacement table (values are constructor
# callables so each mutant builds a fresh operator node).
COMPARISON_SWAPS: dict[type[ast.cmpop], tuple[type[ast.cmpop], ...]] = {
    ast.Lt: (ast.LtE, ast.Gt),
    ast.LtE: (ast.Lt, ast.GtE),
    ast.Gt: (ast.GtE, ast.Lt),
    ast.GtE: (ast.Gt, ast.LtE),
    ast.Eq: (ast.NotEq,),
    ast.NotEq: (ast.Eq,),
    ast.Is: (ast.IsNot,),
    ast.IsNot: (ast.Is,),
    ast.In: (ast.NotIn,),
    ast.NotIn: (ast.In,),
}

# Negation operator sites ("simple conditions" per the lane spec).
_NEGATION_SITES = (ast.If, ast.While, ast.IfExp, ast.Assert)

SENTINEL_MARKER = "mutation-overlay-sentinel"
SENTINEL_SOURCE = f'raise RuntimeError("{SENTINEL_MARKER}")\n'

SITECUSTOMIZE_SOURCE = '''\
"""Mutation-overlay import hook (generated by scripts/mutation_test.py).

Loaded at interpreter startup via PYTHONPATH. Redirects exactly one module --
os.environ["MUTATION_TARGET_MODULE"] -- to the mutated source file at
os.environ["MUTATION_TARGET_FILE"]. Everything else imports normally.
"""

import os
import sys
from importlib.util import spec_from_file_location

_MODULE = os.environ.get("MUTATION_TARGET_MODULE", "")
_FILE = os.environ.get("MUTATION_TARGET_FILE", "")


class _MutationOverlayFinder:
    def find_spec(self, fullname, path=None, target=None):
        if _MODULE and _FILE and fullname == _MODULE:
            return spec_from_file_location(fullname, _FILE)
        return None


if _MODULE and _FILE:
    sys.meta_path.insert(0, _MutationOverlayFinder())
'''


class MutationTestError(ValueError):
    """A fail-closed precondition of the mutation campaign is violated."""


@dataclass(frozen=True)
class Mutant:
    """One candidate mutation of the target source."""

    mutant_id: str
    operator: str
    lineno: int
    description: str
    source: str


@dataclass(frozen=True)
class RunOutcome:
    """Result of one pytest (or stub) invocation."""

    returncode: int | None  # None means the process timed out
    duration_s: float
    output_tail: str = ""


@dataclass(frozen=True)
class MutantResult:
    """Bookkeeping row for one executed mutant."""

    mutant_id: str
    operator: str
    lineno: int
    description: str
    status: str  # killed | survived | timeout | error
    returncode: int | None
    duration_s: float


@dataclass
class CampaignReport:
    """Aggregate campaign outcome serialized to JSON."""

    created_utc: str
    target: str
    module: str
    selectors: tuple[str, ...]
    seed: int
    timeout_s: float
    total_mutants: int
    sampled: int
    counts: dict[str, int] = field(default_factory=dict)
    score: float = 0.0
    min_score: float | None = None
    watermark: str = WATERMARK
    results: list[dict[str, object]] = field(default_factory=list)
    survivors: list[dict[str, object]] = field(default_factory=list)


Runner = Callable[[list[str], Path, dict[str, str], float], RunOutcome]


