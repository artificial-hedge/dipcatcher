#!/usr/bin/env python3
"""Self-contained AST mutation-testing harness (stdlib only; no mutmut/cosmic-ray).

Implements the SOTA roadmap §2.4 item 6 lane: mutation testing on the research
verification layer (``src/quant_fund/research/verify.py`` / ``catalog``). The
harness parses a target module with :mod:`ast`, applies a documented operator
set, and for each mutant overlays the mutated source into the pytest
subprocess's import system **without ever touching the working tree**.

Operator set (each mutant applies exactly one edit to a fresh parse):

* ``comparison-swap`` — ``<``↔``<=``/``>``, ``<=``→``<``/``>=``, ``>``→``>=``/``<``,
  ``>=``→``>``/``<=``, ``==``↔``!=``, ``is``↔``is not``, ``in``↔``not in``.
* ``boolop-swap`` — ``and``↔``or`` on every ``BoolOp``.
* ``numeric-perturb`` — integer constant ``n`` → ``n + 1``; float ``x`` → ``x + 1.0``.
* ``const-bool-flip`` — ``True``↔``False`` constants.
* ``negation-insertion`` — ``if/while/elif/ternary/assert`` test ``t`` → ``not t``.
* ``negation-removal`` — same sites where the test is already ``not t`` → ``t``.

Overlay mechanism: the mutated module is written to a temp dir together with a
generated ``sitecustomize.py`` that installs a ``sys.meta_path`` finder
redirecting exactly one fully-qualified module name to the mutated file.
``sitecustomize`` runs at interpreter startup (before pytest and any
``conftest.py`` can reorder ``sys.path``), and a meta-path finder wins over
path-based resolution — so the overlay is immune to the repo's editable-install
``.pth`` and the root ``conftest.py`` ``sys.path.insert`` of ``src/``.

Fail-closed rules (refuse to run, exit code 2):

* target file missing, not ``.py``, not inside the repo, or not part of an
  importable package (no ``__init__.py`` in its directory);
* pytest selector list empty, blank, option-like (``-`` prefix), or pointing
  outside the repo;
* baseline run (unmutated overlay) does not pass;
* sentinel run (overlay module replaced by a top-level ``raise``) does not
  fail — proves the overlay actually redirects imports *and* that the chosen
  test subset imports the target module at all;
* zero mutants generated, or ``--max-mutants`` < 1, or ``--timeout`` <= 0.

Verdicts per mutant: pytest exit 0 = ``survived``; 1/2/4 (test failures,
collection errors, or a conftest ImportError crash — the baseline run proves
the command line itself is valid, so a 4 during the campaign means the mutant
broke startup imports) = ``killed``; timeout = ``timeout``; 3/5 (pytest
internal error / no tests collected) = ``error`` (harness problem, excluded
from scoring, fails the run closed). Mutation score =
``(killed + timeout) / (sampled - error)``.

Sampling: all mutants are enumerated deterministically (``ast.walk`` order),
then ``--max-mutants`` caps the campaign via a seeded ``random.Random`` sample
(reproducible for a given ``--seed``).

Usage:
    python scripts/mutation_test.py --target src/quant_fund/research/verify.py \
        --pytest tests/unit/research/test_verify_cov.py \
        --max-mutants 20 --seed 7 --json-out /tmp/mutation_report.json
    python scripts/mutation_test.py --target ... --pytest ... --list-mutants

A mutation score is a test-suite diagnostic, not market evidence; no live-PnL
claim.
"""

