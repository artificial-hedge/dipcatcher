def diversity_arbitrage_horizon(mu0: Array, p: float, theta_min: float) -> float:
    """FKK guaranteed-outperformance horizon T* = log D_p(μ_0)/θ_min.

    With Θ ≥ θ_min > 0 the relative log wealth satisfies
    rel_t ≥ θ_min·t − log D_p(μ_0) (since log D_p ≥ 0), so π beats the
    market with certainty for all t > T*. Requires θ_min > 0 (an
    estimated drift floor — the diagnostics, not a promise).
    """
    theta = float(theta_min)
    if not np.isfinite(theta) or theta <= 0.0:
        raise ValueError("theta_min must be finite and positive")
    pv = _check_p(p)
    m = _require_simplex(np.asarray(mu0, dtype=float))
    if m.shape[0] != 1:
        raise ValueError("mu0 must be a single market-weight vector")
    log_d0 = float(np.log(diversity_index(m, pv)[0]))
    if log_d0 <= 0.0:
        raise ValueError("mu0 has no diversity gap to harvest (D_p(μ0) <= 1)")
    return float(log_d0 / theta)


def first_passage_time(values: Array, dt: float, level: float = 0.0) -> float:
    """First t where the (cumulative) path ≥ level; ``nan`` if never."""
    step = _check_dt(dt)
    if not np.isfinite(level):
        raise ValueError("level must be finite")
    v = np.asarray(values, dtype=float).reshape(-1)
    if v.size < 1 or not np.isfinite(v).all():
        raise ValueError("values must be a finite 1-d array")
    hits = np.nonzero(v >= float(level))[0]
    if hits.size == 0:
        return float("nan")
    return float((int(hits[0]) + 1) * step)


def _project_simplex(v: Array) -> Array:
    """Euclidean projection onto the probability simplex (Duchi et al.)."""
    u = np.sort(v)[::-1]
    css = np.cumsum(u) - 1.0
    rho = np.nonzero(u * np.arange(1, v.size + 1) > css)[0]
    if rho.size == 0:
        raise ValueError("simplex projection failed")
    theta = float(css[rho[-1]]) / float(rho[-1] + 1)
    return np.asarray(np.maximum(v - theta, 0.0), dtype=float)


def growth_optimal_weights(
    sigma: Array, n_iter: int = 2000, step_size: float | None = None
) -> Array:
    """argmax over the simplex of the excess growth rate γ*(π).

    Objective γ*(π) = (1/2)(π·diag(σ) − πᵀσπ), numéraire-invariant.
    Deterministic projected-gradient ascent with exact simplex projection;
    step size defaults to 1/λ_max(σ) (descent-safe for the concave
    quadratic objective). σ must be symmetric PSD (fail-closed).
    """
    s = np.asarray(sigma, dtype=float)
    if s.ndim != 2 or s.shape[0] != s.shape[1] or s.shape[0] < 2:
        raise ValueError("sigma must be a square (n >= 2) matrix")
    if not np.isfinite(s).all():
        raise ValueError("sigma must be finite")
    if not np.allclose(s, s.T, atol=1e-10):
        raise ValueError("sigma must be symmetric")
    eig = np.linalg.eigvalsh(s)
    if eig[0] < -1e-8:
        raise ValueError("sigma must be positive semidefinite")
    if isinstance(n_iter, bool) or not isinstance(n_iter, (int, np.integer)) or int(n_iter) < 10:
        raise ValueError("n_iter must be an integer >= 10")
    n_assets = s.shape[0]
    a = np.diag(s).copy()
    lam = float(eig[-1])
    eta = float(step_size) if step_size is not None else (1.0 / lam if lam > 0.0 else 1.0)
    if not np.isfinite(eta) or eta <= 0.0:
        raise ValueError("step_size must be finite and positive")
    pi = np.full(n_assets, 1.0 / n_assets, dtype=float)
    for _ in range(int(n_iter)):
        grad = 0.5 * a - s @ pi
        pi = _project_simplex(pi + eta * grad)
    return np.asarray(pi / pi.sum(), dtype=float)


