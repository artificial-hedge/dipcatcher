def local_time_at_zero(path: Array, dt: float, bandwidth: float | None = None) -> float:
    """Occupation-density local-time estimate at zero of a nonnegative path.

    Λ̂ = (1/(2h)) Σ_k (Δx_k)² · 1{x_k < h}. For a continuous nonnegative
    semimartingale this converges to the semimartingale local time at 0 as
    the grid refines (occupation-density formula). The 1/(2h) normalizer
    and the default bandwidth h = 4·std(Δx) are calibrated against the
    Euler–Skorokhod reflected scheme in ``reflected_path`` where the true
    compensator is known (≈2–5% relative error on bench grids).

    Negative entries beyond ``1e-12`` fail closed — the estimator is only
    meaningful for processes that live on one side of zero (e.g. log rank
    gaps, reflected diffusions).
    """
    x = np.asarray(path, dtype=float).reshape(-1)
    _check_dt(dt)
    if x.size < 2 or not np.isfinite(x).all():
        raise ValueError("path must be a finite 1-d array of length >= 2")
    if np.any(x < -1e-12):
        raise ValueError("path must be nonnegative (one-sided local time at zero)")
    x = np.maximum(x, 0.0)
    increments = np.diff(x)
    if bandwidth is None:
        h = 4.0 * float(np.std(increments))
        if not np.isfinite(h) or h <= 0.0:
            raise ValueError("degenerate increments — cannot pick a bandwidth")
    else:
        h = float(bandwidth)
        if not np.isfinite(h) or h <= 0.0:
            raise ValueError("bandwidth must be finite and positive")
    return float(np.sum((increments**2) * (x[:-1] < h)) / (2.0 * h))


def rank_gap_local_times(mu: Array, dt: float, bandwidth: float | None = None) -> Array:
    """Per-boundary local times Λ̂_{k,k+1} of the log rank gaps, shape (n−1,)."""
    gaps = rank_gaps(mu)
    return np.asarray(
        [local_time_at_zero(gaps[:, k], dt, bandwidth) for k in range(gaps.shape[1])],
        dtype=float,
    )


def reflected_path(x0: float, increments: Array) -> tuple[Array, Array]:
    """Euler–Skorokhod reflected path + its exact discrete compensator.

    R_{k+1} = max(R_k + ε_k, 0), L_{k+1} = L_k + max(−(R_k + ε_k), 0) —
    the standard reflected-diffusion discretization: L accumulates exactly
    the pushes needed to keep R ≥ 0, so it is the scheme's own true local
    time and the honest ground truth for ``local_time_at_zero``.
    """
    start = float(x0)
    if not np.isfinite(start) or start < 0.0:
        raise ValueError("x0 must be finite and nonnegative")
    eps = np.asarray(increments, dtype=float).reshape(-1)
    if eps.size < 1 or not np.isfinite(eps).all():
        raise ValueError("increments must be a finite 1-d array")
    n_steps = eps.size
    r = np.empty(n_steps + 1, dtype=float)
    local = np.empty(n_steps + 1, dtype=float)
    r[0] = start
    local[0] = 0.0
    for k in range(n_steps):
        y = r[k] + float(eps[k])
        r[k + 1] = max(y, 0.0)
        local[k + 1] = local[k] + max(-y, 0.0)
    return r, local


