def simulate_gbm_market(
    n_assets: int = 24,
    n_steps: int = 4096,
    dt: float = 1.0 / 2048.0,
    seed: int = 0,
    *,
    rho: float = 0.4,
    vol_lo: float = 0.30,
    vol_hi: float = 0.90,
    drift_scale: float = 0.05,
    cap_spread: float = 4.0,
) -> Array:
    """Seeded correlated-GBM capitalization panel ``(n_steps+1, n_assets)``.

    d log X_i = (g_i − σ_i²/2)dt + σ_i(√ρ·dW_mkt + √(1−ρ)·dW_i) with
    uniform-parameter grids and log-uniform initial caps spanning
    ``cap_spread`` decades of dispersion. SYNTHETIC correctness world —
    decomposition evidence only, never market evidence.
    """
    for name, value in (("n_assets", n_assets), ("n_steps", n_steps)):
        if isinstance(value, bool) or not isinstance(value, (int, np.integer)) or int(value) < 2:
            raise ValueError(f"{name} must be an integer >= 2")
    step = _check_dt(dt)
    if not np.isfinite(rho) or not 0.0 <= float(rho) < 1.0:
        raise ValueError("rho must lie in [0, 1)")
    if not np.isfinite(vol_lo) or not np.isfinite(vol_hi) or not 0.0 < vol_lo <= vol_hi:
        raise ValueError("vol bounds must satisfy 0 < vol_lo <= vol_hi")
    if not np.isfinite(drift_scale) or float(drift_scale) < 0.0:
        raise ValueError("drift_scale must be finite and nonnegative")
    if not np.isfinite(cap_spread) or float(cap_spread) <= 0.0:
        raise ValueError("cap_spread must be finite and positive")

    rng = np.random.default_rng(_check_seed(seed))
    n = int(n_assets)
    t = int(n_steps)
    vols = rng.uniform(float(vol_lo), float(vol_hi), n)
    drifts = rng.uniform(-float(drift_scale), float(drift_scale), n)
    x0 = np.exp(rng.uniform(-float(cap_spread) / 2.0, float(cap_spread) / 2.0, n))
    common = rng.normal(0.0, 1.0, (t, n))
    idio = rng.normal(0.0, 1.0, (t, n))
    shocks = np.sqrt(float(rho)) * common + np.sqrt(1.0 - float(rho)) * idio
    increments = (drifts[None, :] - 0.5 * vols[None, :] ** 2) * step + (
        vols[None, :] * np.sqrt(step) * shocks
    )
    log_x = np.log(x0)[None, :] + np.vstack([np.zeros((1, n)), np.cumsum(increments, axis=0)])
    caps = np.exp(log_x)
    if not np.isfinite(caps).all() or np.any(caps <= 0.0):
        raise ValueError("simulation produced a degenerate capitalization path")
    return np.asarray(caps, dtype=float)


def arbitrage_diagnostics(
    caps: Array,
    p: float = 0.5,
    dt: float = 1.0 / 252.0,
    margin: float = 0.02,
) -> dict[str, float]:
    """Diversity-vs-cap relative-arbitrage diagnostics on one path.

    Reports the exact relative value path summary (end level and worst
    drawdown), the realized first passage of log(V_π/V_μ) ≥ ``margin``
    (a "strong arbitrage" threshold — crossing 0 alone is trivially fast),
    the realized average drift, the FKK horizon bound T* computed from
    that drift, and the slack ratio T*/realized.
    """
    step = _check_dt(dt)
    pv = _check_p(p)
    x = _require_caps(caps)
    if not np.isfinite(margin) or float(margin) < 0.0:
        raise ValueError("margin must be finite and nonnegative")
    m = market_weights(x)
    pi = diversity_weights(m, pv)
    rel = np.cumsum(relative_log_returns(x, pi))
    theta = diversity_drift_rate(pi[:-1], log_weight_covariation(m, step), pv)
    theta_bar = float(np.mean(theta))
    log_d0 = float(np.log(diversity_index(m[:1], pv)[0]))
    horizon_bound = float(log_d0 / theta_bar) if theta_bar > 0.0 else float("nan")
    realized = first_passage_time(rel, step, float(margin))
    slack = (
        horizon_bound / realized
        if np.isfinite(horizon_bound) and np.isfinite(realized) and realized > 0.0
        else float("nan")
    )
    return {
        "relative_log_wealth_end": float(rel[-1]),
        "relative_log_wealth_min": float(rel.min()),
        "theta_mean": theta_bar,
        "theta_min_step": float(np.min(theta)),
        "log_diversity_start": log_d0,
        "horizon_bound": horizon_bound,
        "horizon_realized": realized,
        "horizon_slack": slack,
    }


def bench_fernholz_spt(seed: int = BENCH_SEED) -> dict[str, float]:
    """Flat dict of SYNTHETIC headline numbers (correctness evidence only).

    Every key is ``synthetic_``-prefixed; values are plain floats. Runs the
    seeded GBM market and the reflected-BM ground truth; reports the
    master-equation residuals (diversity + entropy generators), the
    closed-form vs general drift gap, the local-time estimator error,
    entropy recovery, rank local-time totals, and the arbitrage-horizon
    diagnostics.
    """
    s = _check_seed(seed)
    dt = 1.0 / 2048.0
    caps = simulate_gbm_market(n_assets=24, n_steps=4096, dt=dt, seed=s)
    mu = market_weights(caps)

    # FG decomposition residuals (theory vs exact discrete relative returns).
    p_div = 0.5
    decomp_div = diversity_master_equation(caps, p_div, dt)
    decomp_ent = entropy_master_equation(caps, dt)

    # Closed-form vs general Θ for the D_p generator (should be ~0 gap).
    pi_div = diversity_weights(mu, p_div)
    sigma_mu = log_weight_covariation(mu, dt)
    theta_closed = diversity_drift_rate(pi_div[:-1], sigma_mu, p_div)
    theta_general = fg_drift_rate(
        pi_div[:-1],
        mu[:-1],
        diversity_hess_log_g(mu, p_div)[:-1],
        sigma_mu,
        log_cap_covariation(caps, dt),
    )
    theta_gap = float(np.max(np.abs(theta_closed - theta_general)))

    # Local-time estimator vs exact reflected-path compensator. The
    # estimator is ~unbiased but a single path's local time is a small
    # denominator (few zero visits ⇒ noisy ratio), so pool 12 independent
    # reflections of horizon τ = 4 and compare sums (~4% pooled error).
    rng = np.random.default_rng(s + 1)
    lt_steps, lt_dt = 160_000, 2.5e-5
    est_sum = 0.0
    true_sum = 0.0
    for _ in range(12):
        reflected, true_lt = reflected_path(0.0, rng.normal(0.0, np.sqrt(lt_dt), lt_steps))
        est_sum += local_time_at_zero(reflected, lt_dt, bandwidth=4.0 * np.sqrt(lt_dt))
        true_sum += float(true_lt[-1])
    lt_error = abs(est_sum - true_sum) / true_sum

    # Entropy recovery on a uniform market (exact answer log n).
    n_assets = mu.shape[1]
    uniform = np.full((1, n_assets), 1.0 / n_assets)
    entropy_uniform_error = abs(float(market_entropy(uniform)[0]) - float(np.log(n_assets)))

    # Rank local times + arbitrage diagnostics on the simulated market.
    rank_lts = rank_gap_local_times(mu, dt)
    diag = arbitrage_diagnostics(caps, p_div, dt)
    slack = diag["horizon_slack"]
    return {
        "synthetic_diversity_master_eq_residual": decomp_div.residual_abs,
        "synthetic_diversity_master_eq_rel_residual": decomp_div.residual_rel,
        "synthetic_entropy_master_eq_residual": decomp_ent.residual_abs,
        "synthetic_entropy_master_eq_rel_residual": decomp_ent.residual_rel,
        "synthetic_theta_closed_form_gap": theta_gap,
        "synthetic_diversity_theta_integral": decomp_div.theta_integral,
        "synthetic_entropy_theta_integral": decomp_ent.theta_integral,
        "synthetic_local_time_rel_error": float(lt_error),
        "synthetic_entropy_uniform_error": float(entropy_uniform_error),
        "synthetic_rank_local_time_max": float(np.max(rank_lts)),
        "synthetic_rank_local_time_sum": float(np.sum(rank_lts)),
        "synthetic_relative_log_wealth_end": diag["relative_log_wealth_end"],
        "synthetic_relative_log_wealth_min": diag["relative_log_wealth_min"],
        "synthetic_theta_mean": diag["theta_mean"],
        "synthetic_horizon_bound": diag["horizon_bound"],
        "synthetic_horizon_realized": float(diag["horizon_realized"])
        if np.isfinite(diag["horizon_realized"])
        else float(caps.shape[0] - 1) * dt,
        "synthetic_horizon_slack": float(slack) if np.isfinite(slack) else float("nan"),
    }


